// Read-only atlas analysis: the ImageGen artwork is never repainted, cropped or repacked.
// Emit CSS texture coordinates/clip rectangles so irregular generated gutters cannot bleed.
import { createRequire } from 'node:module'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import prettierConfig from '../../packages/config/prettier/index.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const sharp = createRequire(resolve(root, 'apps/api/package.json'))('sharp')
const prettier = createRequire(resolve(root, 'apps/api/package.json'))('prettier')
const directory = resolve(root, 'apps/web/src/features/personal/assets')
const output = resolve(root, 'apps/web/src/features/personal/pomodoro-atlas.css')
const median = (values) => [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)]
const round = (n) => Number(n.toFixed(5))
const css = [
  '/* Generated by tools/assets/pomodoro-atlas.mjs. Original pixels remain untouched. */',
]
const reports = []
for (const file of readdirSync(directory).filter((name) => name.endsWith('-sprite.webp'))) {
  const name = file.replace('-sprite.webp', '')
  const {
    data,
    info: { width, height, channels },
  } = await sharp(resolve(directory, file)).raw().toBuffer({ resolveWithObject: true })
  if (width !== 1536 || height !== 1024 || channels !== 4) throw new Error(`${name}: invalid sheet`)
  const alpha = (x, y) => data[(y * width + x) * 4 + 3]
  const cuts = []
  function boundary(nominal, scan) {
    let best = nominal,
      bestScore = Infinity,
      countAtBest = 0
    for (let position = nominal - 80; position <= nominal + 80; position++) {
      const count = scan(position)
      const score = count + Math.abs(position - nominal) / 10000
      if (score < bestScore) {
        best = position
        bestScore = score
        countAtBest = count
      }
    }
    cuts.push(countAtBest)
    return best
  }
  const rows = [
    0,
    ...[256, 512, 768].map((nominal) =>
      boundary(nominal, (y) => {
        let count = 0
        for (let x = 0; x < width; x++) if (alpha(x, y) > 32) count++
        return count
      }),
    ),
    height,
  ]
  const frames = []
  for (let row = 0; row < 4; row++) {
    const top = rows[row],
      bottom = rows[row + 1]
    const columns = [
      0,
      ...[256, 512, 768, 1024, 1280].map((nominal) =>
        boundary(nominal, (x) => {
          let count = 0
          for (let y = top; y < bottom; y++) if (alpha(x, y) > 32) count++
          return count
        }),
      ),
      width,
    ]
    for (let column = 0; column < 6; column++) {
      const left = columns[column],
        right = columns[column + 1]
      let minX = right,
        maxX = left,
        minY = bottom,
        maxY = top
      let redMinX = right,
        redMaxX = left,
        redMinY = bottom,
        redMaxY = top
      for (let y = top; y < bottom; y++)
        for (let x = left; x < right; x++) {
          const offset = (y * width + x) * 4
          if (data[offset + 3] < 64) continue
          minX = Math.min(minX, x)
          maxX = Math.max(maxX, x)
          minY = Math.min(minY, y)
          maxY = Math.max(maxY, y)
          if (data[offset] > data[offset + 1] * 1.5 && data[offset] > data[offset + 2] * 1.4) {
            redMinX = Math.min(redMinX, x)
            redMaxX = Math.max(redMaxX, x)
            redMinY = Math.min(redMinY, y)
            redMaxY = Math.max(redMaxY, y)
          }
        }
      if (redMaxX - redMinX < 60 || redMaxY - redMinY < 60)
        throw new Error(`${name}: missing tomato in frame ${frames.length + 1}`)
      frames.push({
        row,
        column,
        left,
        right,
        top,
        bottom,
        minX,
        maxX,
        minY,
        maxY,
        redMinX,
        redMaxX,
        redMinY,
        redMaxY,
      })
    }
  }
  // Use one scale per sheet and one baseline per row; retain in-between motion within each row.
  const anchorsX = Array.from({ length: 6 }, (_, column) =>
    median(frames.filter((f) => f.column === column).map((f) => (f.redMinX + f.redMaxX) / 2)),
  )
  const anchorsY = Array.from({ length: 4 }, (_, row) =>
    median(frames.filter((f) => f.row === row).map((f) => f.redMaxY)),
  )
  let scale = Math.min(
    150 / median(frames.map((f) => f.redMaxX - f.redMinX)),
    150 / median(frames.map((f) => f.redMaxY - f.redMinY)),
  )
  for (const f of frames) {
    const x = anchorsX[f.column],
      y = anchorsY[f.row]
    scale = Math.min(
      scale,
      120 / Math.max(x - f.minX, f.maxX - x),
      208 / Math.max(1, y - f.minY),
      32 / Math.max(1, f.maxY - y),
    )
  }
  const styles = frames.map((f) => {
    const x = 128 - anchorsX[f.column] * scale,
      y = 216 - anchorsY[f.row] * scale
    const position = `${round((x / (256 - width * scale)) * 100)}% ${round((y / (256 - height * scale)) * 100)}%`
    const inset = [
      y + f.top * scale,
      256 - (x + f.right * scale),
      256 - (y + f.bottom * scale),
      x + f.left * scale,
    ]
      .map((n) => `${round((Math.max(0, n) / 256) * 100)}%`)
      .join(' ')
    return `background-position: ${position}; clip-path: inset(${inset});`
  })
  css.push(
    `.pomodoro-character-sprite[data-sequence='${name}'] { --tomato-frames: pomodoro-character-frames-${name}; background-size: ${round(((width * scale) / 256) * 100)}% ${round(((height * scale) / 256) * 100)}%; ${styles[0]} }`,
  )
  css.push(
    `.pomodoro-character-layer[data-active='false'] .pomodoro-character-sprite[data-sequence='${name}'] { ${styles.at(-1)} }`,
  )
  css.push(`@keyframes pomodoro-character-frames-${name} {`)
  styles.forEach((style, i) => css.push(`  ${round((i / 24) * 100)}% { ${style} }`))
  css.push(`  100% { ${styles.at(-1)} }`, '}')
  reports.push({
    name,
    frames: frames.length,
    scale: round(scale),
    cutPixels: cuts.reduce((a, b) => a + b, 0),
  })
}
if (reports.some((r) => r.cutPixels > 0))
  throw new Error(
    `Nontransparent atlas boundaries: ${JSON.stringify(reports.filter((r) => r.cutPixels > 0))}`,
  )
const contents = await prettier.format(css.join('\n') + '\n', {
  ...prettierConfig,
  parser: 'css',
})
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== contents)
    throw new Error('Pomodoro atlas CSS is stale; regenerate it')
} else writeFileSync(output, contents)
console.log(JSON.stringify(reports, null, 2))
